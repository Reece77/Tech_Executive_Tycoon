// Regenerates src/api from the backend OpenAPI schema (ADR-0009).
// 1. Export openapi.json from the FastAPI app without starting a server.
// 2. Run openapi-typescript to write src/api/schema.d.ts.
// 3. Write the openapi-fetch wrapper src/api/client.ts.
// Everything in src/api is generated: never hand-edit it.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backendDir = resolve(frontendDir, '..', 'backend');
const apiDir = join(frontendDir, 'src', 'api');
const specPath = join(apiDir, 'openapi.json');

const HEADER = '// GENERATED by `pnpm gen:api` from the backend OpenAPI schema. Do not edit.\n';

mkdirSync(apiDir, { recursive: true });

execFileSync('uv', ['run', 'python', 'scripts/export_openapi.py', specPath], {
  cwd: backendDir,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const ast = await openapiTS(spec);
writeFileSync(join(apiDir, 'schema.d.ts'), HEADER + astToString(ast));

writeFileSync(
  join(apiDir, 'client.ts'),
  HEADER +
    `import createClient from 'openapi-fetch';
import type { components, paths } from './schema';

export type Schemas = components['schemas'];

export const api = createClient<paths>({ baseUrl: '' });
`,
);

console.log('Regenerated src/api (openapi.json, schema.d.ts, client.ts)');
